/** 把精简字段展开成页面使用的完整故事结构 */
export function buildStoryFromBrief(symbol, brief) {
    const element = getElementBySymbol(symbol)
    const name = element?.name || symbol
    const sourceTitle = brief.s || name
    const category = (ELEMENT_CATEGORIES[element?.category] || ELEMENT_CATEGORIES.unknown).label
    const fallbackIntro = element
        ? `${name}是第 ${element.period} 周期${element.group ? `第 ${element.group} 族` : "镧系/锕系"}的${category}元素。`
        : `${name}是元素周期表里的第 ${symbol} 号成员。`

    return {
        intro: brief.i || fallbackIntro,
        discovery: {
            year: brief.y || "",
            title: brief.dt || `${name}的发现`,
            text: brief.d || "",
        },
        occurrence: brief.o || "",
        narrative: brief.n || "",
        applications: (brief.a || []).map(item => {
            const text = String(item)
            const index = text.indexOf("：")
            return index > 0
                ? { title: text.slice(0, index), text: text.slice(index + 1) }
                : { title: text, text: "" }
        }),
        reactions: (brief.r || []).map(reaction => ({
            equation: reaction.e,
            condition: reaction.c || "",
            phenomenon: reaction.p || "",
            meaning: reaction.m || "",
            safety: reaction.s || "",
        })),
        question: brief.q || "",
        source: {
            label: `维基百科 · ${sourceTitle}`,
            url: `https://zh.wikipedia.org/wiki/${encodeURIComponent(sourceTitle)}`,
        },
    }
}
